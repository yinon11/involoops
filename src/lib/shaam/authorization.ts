/**
 * Authorization lifecycle service for SHAAM OAuth (Spec 07).
 *
 * All DB writes inside `completeAuthorization` / `getActiveAccessToken`
 * / `revokeAuthorization` are wrapped in a transaction with
 * `SELECT ... FOR UPDATE` on the authorization row so that concurrent
 * refreshes against the same (business_entity, environment) collapse
 * into exactly one network round trip.
 */

import { and, eq } from "drizzle-orm";
import { db } from "@/db";
import {
  shaamAuthorizations,
  shaamTokenEvents,
  shaamAuthorizationPending,
} from "@/db/schema";
import type {
  ShaamEnvironment,
  ShaamAuthorizationStatus,
} from "@/db/schema/shaam-authorizations";
import type { ShaamTokenEventType } from "@/db/schema/shaam-token-events";
import {
  buildAuthorizationUrl,
  exchangeAuthorizationCode,
  getShaamConfig,
  refreshAccessToken,
  revokeToken,
  sanitizeTokenResponseForLogging,
  type TokenResponse,
} from "./client";
import { ShaamApiError, ShaamAuthorizationError } from "./errors";
import {
  codeChallengeFrom,
  generateCodeVerifier,
  generateState,
} from "./pkce";
import { decryptToken, encryptToken } from "./token-crypto";
import { prefix, shaamError, shaamLog } from "./debug";
import { getShaamProxyHostPort } from "./proxy";

const ACCESS_TOKEN_REFRESH_LEEWAY_MS = 5 * 60 * 1000;
const REFRESH_TOKEN_LIFETIME_MS = 90 * 24 * 60 * 60 * 1000;
const PENDING_TTL_MS = 15 * 60 * 1000;

export interface InitiateResult {
  authorizationUrl: string;
  state: string;
  environment: ShaamEnvironment;
}

export async function initiateAuthorization(params: {
  businessEntityId: string;
  actorUserId: string;
  environment?: ShaamEnvironment;
}): Promise<InitiateResult> {
  const cfg = getShaamConfig();
  const environment = params.environment ?? cfg.environment;
  const verifier = generateCodeVerifier();
  const challenge = codeChallengeFrom(verifier);
  const state = generateState();
  const now = new Date();

  shaamLog("authorization.initiate", "start", {
    business_entity_id: params.businessEntityId,
    actor_user_id: params.actorUserId,
    environment,
    base_url: cfg.baseUrl,
    redirect_uri: cfg.redirectUri,
    scope: cfg.scope,
    state_prefix: prefix(state, 8),
    proxy: getShaamProxyHostPort() ?? null,
  });

  await db.transaction(async (tx) => {
    await tx
      .insert(shaamAuthorizations)
      .values({
        businessEntityId: params.businessEntityId,
        environment,
        status: "PENDING" satisfies ShaamAuthorizationStatus,
      })
      .onConflictDoUpdate({
        target: [
          shaamAuthorizations.businessEntityId,
          shaamAuthorizations.environment,
        ],
        set: {
          status: "PENDING" satisfies ShaamAuthorizationStatus,
          updatedAt: now,
        },
      });
    await tx.insert(shaamAuthorizationPending).values({
      businessEntityId: params.businessEntityId,
      environment,
      state,
      codeVerifier: verifier,
      initiatedByUserId: params.actorUserId,
      expiresAt: new Date(now.getTime() + PENDING_TTL_MS),
    });
  });

  const authorizationUrl = buildAuthorizationUrl({
    state,
    codeChallenge: challenge,
    config: { ...cfg, environment },
  });
  shaamLog("authorization.initiate", "ready — redirecting browser to ITA", {
    business_entity_id: params.businessEntityId,
    environment,
    state_prefix: prefix(state, 8),
  });
  return { authorizationUrl, state, environment };
}

export interface CompleteResult {
  businessEntityId: string;
  environment: ShaamEnvironment;
  status: "ACTIVE";
}

export async function completeAuthorization(params: {
  state: string;
  code: string;
  environment?: ShaamEnvironment;
}): Promise<CompleteResult> {
  shaamLog("authorization.complete", "callback received", {
    state_prefix: prefix(params.state, 8),
    code_prefix: prefix(params.code, 6),
    environment_override: params.environment ?? null,
  });
  const pendingRows = await db
    .select()
    .from(shaamAuthorizationPending)
    .where(eq(shaamAuthorizationPending.state, params.state))
    .limit(1);
  const pending = pendingRows[0];
  if (!pending) {
    shaamError(
      "authorization.complete",
      "no pending row matched state — was the state generated by a different deployment, or was the row already consumed?",
      { state_prefix: prefix(params.state, 8) },
    );
    throw new ShaamApiError(400, "invalid_state", "Unknown state", null);
  }
  if (pending.expiresAt.getTime() < Date.now()) {
    shaamError("authorization.complete", "pending state expired", {
      state_prefix: prefix(params.state, 8),
      expired_at: pending.expiresAt.toISOString(),
      ttl_minutes: PENDING_TTL_MS / 60_000,
    });
    await db
      .delete(shaamAuthorizationPending)
      .where(eq(shaamAuthorizationPending.id, pending.id));
    throw new ShaamApiError(400, "invalid_state", "State expired", null);
  }

  const environment = params.environment ?? pending.environment;
  const cfg = getShaamConfig();
  shaamLog("authorization.complete", "exchanging code for tokens", {
    business_entity_id: pending.businessEntityId,
    environment,
    base_url: cfg.baseUrl,
    token_path: cfg.tokenPath,
    redirect_uri: cfg.redirectUri,
    proxy: getShaamProxyHostPort() ?? null,
  });
  let token: TokenResponse;
  try {
    token = await exchangeAuthorizationCode({
      code: params.code,
      codeVerifier: pending.codeVerifier,
      config: { ...cfg, environment },
    });
  } catch (err) {
    if (err instanceof ShaamApiError) {
      shaamError(
        "authorization.complete",
        "token exchange failed — see [shaam:oauth.post] above for the wire-level detail",
        {
          business_entity_id: pending.businessEntityId,
          environment,
          http_status: err.httpStatus,
          ita_error_code: err.itaErrorCode,
          ita_message: err.itaMessage,
          request_id: err.requestId,
        },
      );
    } else {
      shaamError("authorization.complete", "token exchange threw non-API error", {
        business_entity_id: pending.businessEntityId,
        environment,
        message: err instanceof Error ? err.message : String(err),
      });
    }
    throw err;
  }
  shaamLog("authorization.complete", "token exchange succeeded", {
    business_entity_id: pending.businessEntityId,
    environment,
    expires_in: token.expires_in,
    scope: token.scope ?? null,
    token_type: token.token_type,
  });

  const now = new Date();
  await db.transaction(async (tx) => {
    const accessExpiresAt = new Date(
      now.getTime() + token.expires_in * 1000,
    );
    const refreshExpiresAt = new Date(now.getTime() + REFRESH_TOKEN_LIFETIME_MS);
    const encAccess = encryptToken(token.access_token);
    const encRefresh = encryptToken(token.refresh_token);

    await tx
      .update(shaamAuthorizations)
      .set({
        status: "ACTIVE",
        refreshTokenEncrypted: encRefresh.ciphertext,
        refreshTokenIv: encRefresh.iv,
        refreshTokenTag: encRefresh.tag,
        refreshTokenExpiresAt: refreshExpiresAt,
        accessTokenEncrypted: encAccess.ciphertext,
        accessTokenIv: encAccess.iv,
        accessTokenTag: encAccess.tag,
        accessTokenExpiresAt: accessExpiresAt,
        scope: token.scope ?? null,
        authorizedAt: now,
        lastRefreshedAt: now,
        lastErrorCode: null,
        lastErrorMessage: null,
        lastErrorAt: null,
        updatedAt: now,
      })
      .where(
        and(
          eq(shaamAuthorizations.businessEntityId, pending.businessEntityId),
          eq(shaamAuthorizations.environment, environment),
        ),
      );

    await tx
      .delete(shaamAuthorizationPending)
      .where(eq(shaamAuthorizationPending.id, pending.id));

    await logTokenEventTx(
      tx,
      pending.businessEntityId,
      environment,
      "AUTHORIZATION_GRANTED",
      {
        metadata: {
          ...sanitizeTokenResponseForLogging(token),
          refresh_token_expires_at: refreshExpiresAt.toISOString(),
          access_token_expires_at: accessExpiresAt.toISOString(),
        },
      },
    );
  });

  return {
    businessEntityId: pending.businessEntityId,
    environment,
    status: "ACTIVE",
  };
}

/**
 * Return a valid access token string for (businessEntityId,
 * environment). Refreshes proactively when the cached token is within
 * the leeway window of expiry; refreshes reactively when it has
 * already expired. Serialises concurrent callers via
 * `SELECT ... FOR UPDATE` on the authorization row.
 */
export async function getActiveAccessToken(params: {
  businessEntityId: string;
  environment?: ShaamEnvironment;
}): Promise<string> {
  const cfg = getShaamConfig();
  const environment = params.environment ?? cfg.environment;
  const result = await db.transaction(async (tx) => {
    // Typed select with FOR UPDATE — drizzle maps snake_case columns
    // back to their camelCase field names via the schema metadata.
    // A raw `tx.execute(sql\`SELECT *\`)` bypasses that mapping and
    // returns the postgres-js wire-format keys (access_token_expires_at,
    // refresh_token_encrypted, …), which silently broke every access
    // downstream and made `getActiveAccessToken` throw `expired` on
    // first call.
    const rows = await tx
      .select()
      .from(shaamAuthorizations)
      .where(
        and(
          eq(shaamAuthorizations.businessEntityId, params.businessEntityId),
          eq(shaamAuthorizations.environment, environment),
        ),
      )
      .for("update")
      .limit(1);
    const row = rows[0];
    if (!row) {
      throw new ShaamAuthorizationError(
        "never_authorized",
        params.businessEntityId,
      );
    }
    if (row.status === "PENDING") {
      throw new ShaamAuthorizationError("pending", params.businessEntityId);
    }
    if (row.status === "EXPIRED") {
      throw new ShaamAuthorizationError("expired", params.businessEntityId);
    }
    if (row.status === "REVOKED") {
      throw new ShaamAuthorizationError("revoked", params.businessEntityId);
    }
    if (row.status === "ERROR") {
      throw new ShaamAuthorizationError("error", params.businessEntityId);
    }

    const now = Date.now();
    const accessStillValid =
      row.accessTokenEncrypted &&
      row.accessTokenIv &&
      row.accessTokenTag &&
      row.accessTokenExpiresAt &&
      row.accessTokenExpiresAt.getTime() - now >
        ACCESS_TOKEN_REFRESH_LEEWAY_MS;

    if (accessStillValid) {
      return {
        kind: "ok" as const,
        access: decryptToken({
          ciphertext: row.accessTokenEncrypted!,
          iv: row.accessTokenIv!,
          tag: row.accessTokenTag!,
        }),
      };
    }

    if (
      !row.refreshTokenEncrypted ||
      !row.refreshTokenIv ||
      !row.refreshTokenTag
    ) {
      throw new ShaamAuthorizationError("expired", params.businessEntityId);
    }
    const refreshToken = decryptToken({
      ciphertext: row.refreshTokenEncrypted,
      iv: row.refreshTokenIv,
      tag: row.refreshTokenTag,
    });

    let tokenResponse: TokenResponse;
    try {
      tokenResponse = await refreshAccessToken({
        refreshToken,
        config: { ...cfg, environment },
      });
    } catch (err) {
      // Persist the failure marker (status → EXPIRED/ERROR + event
      // log) inside the current tx, then RETURN a deferred throw
      // instead of throwing. Throwing here would make drizzle roll
      // back the outer tx — including the `markRefreshFailure`
      // write — leaving status=ACTIVE on disk even though we
      // reported `expired` to the caller. Returning commits the
      // failure marker; the caller (outside the tx) throws.
      await markRefreshFailure(tx, row, environment, err);
      const deferred =
        err instanceof ShaamApiError && err.httpStatus === 401
          ? new ShaamAuthorizationError(
              "expired",
              params.businessEntityId,
              err,
            )
          : (err as Error);
      return { kind: "deferredThrow" as const, err: deferred };
    }

    const refreshedNow = new Date();
    const accessExpiresAt = new Date(
      refreshedNow.getTime() + tokenResponse.expires_in * 1000,
    );
    const encAccess = encryptToken(tokenResponse.access_token);
    const rotated = tokenResponse.refresh_token !== refreshToken;
    const encRefresh = rotated
      ? encryptToken(tokenResponse.refresh_token)
      : null;
    const refreshExpiresAt = rotated
      ? new Date(refreshedNow.getTime() + REFRESH_TOKEN_LIFETIME_MS)
      : (row.refreshTokenExpiresAt ?? null);

    await tx
      .update(shaamAuthorizations)
      .set({
        accessTokenEncrypted: encAccess.ciphertext,
        accessTokenIv: encAccess.iv,
        accessTokenTag: encAccess.tag,
        accessTokenExpiresAt: accessExpiresAt,
        ...(encRefresh
          ? {
              refreshTokenEncrypted: encRefresh.ciphertext,
              refreshTokenIv: encRefresh.iv,
              refreshTokenTag: encRefresh.tag,
              refreshTokenExpiresAt: refreshExpiresAt,
            }
          : {}),
        lastRefreshedAt: refreshedNow,
        lastErrorCode: null,
        lastErrorMessage: null,
        lastErrorAt: null,
        updatedAt: refreshedNow,
        status: "ACTIVE",
      })
      .where(eq(shaamAuthorizations.id, row.id));

    await logTokenEventTx(
      tx,
      row.businessEntityId,
      environment,
      "ACCESS_TOKEN_REFRESHED",
      {
        metadata: {
          ...sanitizeTokenResponseForLogging(tokenResponse),
          rotated,
          access_token_expires_at: accessExpiresAt.toISOString(),
        },
      },
    );
    if (rotated) {
      await logTokenEventTx(
        tx,
        row.businessEntityId,
        environment,
        "REFRESH_TOKEN_ROTATED",
        {
          metadata: {
            refresh_token_expires_at:
              refreshExpiresAt?.toISOString() ?? null,
          },
        },
      );
    }

    return { kind: "ok" as const, access: tokenResponse.access_token };
  });
  if (result.kind === "deferredThrow") throw result.err;
  return result.access;
}

async function markRefreshFailure(
  tx: Parameters<Parameters<typeof db.transaction>[0]>[0],
  row: typeof shaamAuthorizations.$inferSelect,
  environment: ShaamEnvironment,
  err: unknown,
): Promise<void> {
  const now = new Date();
  const apiErr = err instanceof ShaamApiError ? err : null;
  const code = apiErr?.itaErrorCode ?? "refresh_failed";
  const message =
    apiErr?.itaMessage ?? (err instanceof Error ? err.message : String(err));

  const newStatus: ShaamAuthorizationStatus =
    apiErr?.httpStatus === 401 ? "EXPIRED" : "ERROR";

  await tx
    .update(shaamAuthorizations)
    .set({
      status: newStatus,
      lastErrorCode: code,
      lastErrorMessage: message,
      lastErrorAt: now,
      updatedAt: now,
    })
    .where(eq(shaamAuthorizations.id, row.id));

  const eventType: ShaamTokenEventType =
    newStatus === "EXPIRED" ? "AUTHORIZATION_EXPIRED" : "REFRESH_FAILED";
  await logTokenEventTx(tx, row.businessEntityId, environment, eventType, {
    httpStatus: apiErr?.httpStatus ?? null,
    errorCode: code,
    errorMessage: message,
  });
}

export async function revokeAuthorization(params: {
  businessEntityId: string;
  actorUserId: string;
  environment?: ShaamEnvironment;
}): Promise<void> {
  const cfg = getShaamConfig();
  const environment = params.environment ?? cfg.environment;
  const rows = await db
    .select()
    .from(shaamAuthorizations)
    .where(
      and(
        eq(shaamAuthorizations.businessEntityId, params.businessEntityId),
        eq(shaamAuthorizations.environment, environment),
      ),
    )
    .limit(1);
  const row = rows[0];
  if (!row) return;

  if (row.refreshTokenEncrypted && row.refreshTokenIv && row.refreshTokenTag) {
    try {
      const refreshToken = decryptToken({
        ciphertext: row.refreshTokenEncrypted,
        iv: row.refreshTokenIv,
        tag: row.refreshTokenTag,
      });
      await revokeToken({
        token: refreshToken,
        tokenTypeHint: "refresh_token",
        config: { ...cfg, environment },
      });
    } catch {
      /* best-effort */
    }
  }
  if (row.accessTokenEncrypted && row.accessTokenIv && row.accessTokenTag) {
    try {
      const accessToken = decryptToken({
        ciphertext: row.accessTokenEncrypted,
        iv: row.accessTokenIv,
        tag: row.accessTokenTag,
      });
      await revokeToken({
        token: accessToken,
        tokenTypeHint: "access_token",
        config: { ...cfg, environment },
      });
    } catch {
      /* best-effort */
    }
  }

  const now = new Date();
  await db.transaction(async (tx) => {
    await tx
      .update(shaamAuthorizations)
      .set({
        status: "REVOKED",
        refreshTokenEncrypted: null,
        refreshTokenIv: null,
        refreshTokenTag: null,
        refreshTokenExpiresAt: null,
        accessTokenEncrypted: null,
        accessTokenIv: null,
        accessTokenTag: null,
        accessTokenExpiresAt: null,
        updatedAt: now,
      })
      .where(eq(shaamAuthorizations.id, row.id));
    await logTokenEventTx(
      tx,
      row.businessEntityId,
      environment,
      "TOKEN_REVOKED",
      { metadata: { actorUserId: params.actorUserId } },
    );
  });
}

async function logTokenEventTx(
  tx: Parameters<Parameters<typeof db.transaction>[0]>[0],
  businessEntityId: string,
  environment: ShaamEnvironment,
  eventType: ShaamTokenEventType,
  fields: {
    httpStatus?: number | null;
    errorCode?: string | null;
    errorMessage?: string | null;
    metadata?: Record<string, unknown>;
  } = {},
): Promise<void> {
  await tx.insert(shaamTokenEvents).values({
    businessEntityId,
    environment,
    eventType,
    httpStatus: fields.httpStatus ?? null,
    errorCode: fields.errorCode ?? null,
    errorMessage: fields.errorMessage ?? null,
    metadata: fields.metadata ?? null,
  });
}

/**
 * Spec 11 §4 — lightweight presence check for the issue confirmation
 * modal. Returns true iff there is an ACTIVE row for the business
 * entity in the configured environment. No token decryption or
 * refresh side-effects — just a row read.
 */
export async function hasActiveAuthorization(
  businessEntityId: string,
  environment?: ShaamEnvironment,
): Promise<boolean> {
  const cfg = getShaamConfig();
  const env = environment ?? cfg.environment;
  const rows = await db
    .select({ id: shaamAuthorizations.id })
    .from(shaamAuthorizations)
    .where(
      and(
        eq(shaamAuthorizations.businessEntityId, businessEntityId),
        eq(shaamAuthorizations.environment, env),
        eq(shaamAuthorizations.status, "ACTIVE"),
      ),
    )
    .limit(1);
  return rows.length > 0;
}
